/* --- Runtime API --- */
window.HandsI18n.lang = function () {
  return localStorage.getItem("hands-lang") || "es";
};

window.HandsI18n.dict = function () {
  var lang = window.HandsI18n.lang();
  return window.HandsI18n[lang] || window.HandsI18n.es;
};

/** Apply dictionary strings to data-i18n / data-i18n-placeholder nodes and lang toggles. */
window.HandsI18n.apply = function () {
  var lang = window.HandsI18n.lang();
  var dict = window.HandsI18n.dict();
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(function (el) {
    var key = el.getAttribute("data-i18n");
    if (dict[key]) el.textContent = dict[key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
    var key = el.getAttribute("data-i18n-placeholder");
    if (dict[key]) el.setAttribute("placeholder", dict[key]);
  });
  document.querySelectorAll(".lang-btn").forEach(function (btn) {
    btn.classList.toggle("is-active", btn.getAttribute("data-lang") === lang);
  });
  return dict;
};
